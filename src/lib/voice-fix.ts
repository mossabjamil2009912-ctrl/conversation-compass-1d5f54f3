// Instant cleanup of spoken (dialect) questions before they show in the chat bubble:
// dialect numbers -> digits and common brand mis-hearings -> correct names.
const NUMS: [RegExp, string][] = [
  [/(?:إ|ا)حدعشر|حداعش(?:ر)?/g, "11"],
  [/(?:إ|ا)ثنعشر|اطنعش(?:ر)?|اثناعش(?:ر)?/g, "12"],
  [/ثلاث?طعش(?:ر)?|تلطعش(?:ر)?|ثلاثتعشر/g, "13"],
  [/(?:ا|أ)ربع?طعش(?:ر)?|اربعتعشر/g, "14"],
  [/خمس?طعش(?:ر)?|خمستعشر/g, "15"],
  [/س[تط]?طعش(?:ر)?|ستعش(?:ر)?|سطعش(?:ر)?|ستتعشر/g, "16"],
  [/سبع?طعش(?:ر)?|سبعتعشر/g, "17"],
  [/ثمن?طعش(?:ر)?|تمنطعش(?:ر)?|ثمانتعشر/g, "18"],
  [/تسع?طعش(?:ر)?|تسعتعشر/g, "19"],
  [/(?:^|\s)عشرين(?=\s|$|[.؟?،])/g, " 20"],
  [/(?:^|\s)ثلاثين(?=\s|$|[.؟?،])/g, " 30"],
  [/(?:^|\s)(?:أ|ا)ربعين(?=\s|$|[.؟?،])/g, " 40"],
  [/(?:^|\s)خمسين(?=\s|$|[.؟?،])/g, " 50"],
];
const BRANDS: [RegExp, string][] = [
  [/ف[يى]د[وو]?[زسص]|ف[يى]ل[يى]?ست[يى]/g, "فيدوس"],
  [/سول[يى]?[سزص](?![ا-ي])/g, "سوليس"],
  [/(?:^|\s)(?:دا[يى]|ديي|دايه)(?=\s|$)/g, " دِيِه"],
  [/لون[جغق][يى]/g, "لونجي"],
  [/صنتك|سنتك/g, "سانتك"],
  [/بايلونتك|بيلونتك/g, "بايلونتك"],
];
export function fixVoiceText(s: string): string {
  let t = s;
  for (const [r, v] of NUMS) t = t.replace(r, v);
  for (const [r, v] of BRANDS) t = t.replace(r, v);
  return t.replace(/[.。]+$/, "").replace(/\s+/g, " ").trim();
}
